"use strict";

// Version-free host integration: a stable launcher outside the versioned extension folder,
// nested Git repository discovery, and migration of agent-host .mcp.json entries.
const path = require("node:path");
const fs = require("node:fs/promises");
const { randomUUID } = require("node:crypto");

const SKIPPED = new Set(["node_modules", "dist", "build", "out", "coverage", "vendor", "target"]);
const MAX_REPOSITORIES = 64;

/** Finds independent Git repositories (folders holding `.git`) below ROOT, ROOT excluded. */
async function discoverRepositories(root, maxDepth = 3) {
  const found = [];
  async function walk(directory, depth) {
    if (depth > maxDepth || found.length >= MAX_REPOSITORIES) return;
    let entries;
    try { entries = await fs.readdir(directory, { withFileTypes: true }); } catch { return; }
    for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
      if (!entry.isDirectory() || entry.isSymbolicLink() || entry.name.startsWith(".") || SKIPPED.has(entry.name)) continue;
      const child = path.join(directory, entry.name);
      // `.git` is a folder for clones and a file for submodules and worktrees.
      if (await fs.stat(path.join(child, ".git")).then(() => true, () => false)) {
        found.push({ path: path.relative(root, child).split(path.sep).join("/") });
        if (found.length >= MAX_REPOSITORIES) return;
      }
      await walk(child, depth + 1);
    }
  }
  await walk(root, 1);
  return found;
}

/** Declared repositories first (they carry name/gitUrl/branch), then discovered ones not yet declared. */
function mergeRepositories(declared, discovered) {
  const known = new Set(declared.map(item => item.path.replace(/\/+$/, "")));
  return [...declared, ...discovered.filter(item => !known.has(item.path))].slice(0, MAX_REPOSITORIES);
}

// One installation at a time per process: activation, settings changes and Autoconfig can overlap.
let installing = Promise.resolve();
/** Writes launchers whose path never changes; each activation re-points them at the running version. */
function installLauncher(extensionPath, storagePath) {
  const run = installing.then(() => writeLauncher(extensionPath, storagePath));
  installing = run.catch(() => undefined);
  return run;
}
async function writeLauncher(extensionPath, storagePath) {
  const bin = path.join(storagePath, "bin");
  await fs.mkdir(bin, { recursive: true, mode: 0o700 });
  const windows = process.platform === "win32";
  const node = path.join(extensionPath, "runtime", windows ? "node.exe" : "node");
  const entry = path.join(extensionPath, "stdio.cjs");
  const launcher = path.join(bin, windows ? "kimono-mcp.cmd" : "kimono-mcp");
  const content = windows
    ? `@echo off\r\n"${node}" "${entry}" %*\r\n`
    : `#!/bin/sh\n# Generated by the Kimono VS Code extension; rewritten on every activation.\nexec '${node.replace(/'/g, "'\\''")}' '${entry.replace(/'/g, "'\\''")}' "$@"\n`;
  // Already current (same extension version): nothing to write.
  if (await fs.readFile(launcher, "utf8").then(current => current === content, () => false)) return launcher;
  // Unique temporary name: another process (a second VS Code window) may be writing at the same time.
  const temporary = `${launcher}.${process.pid}.${randomUUID()}.tmp`;
  try {
    await fs.writeFile(temporary, content, { mode: 0o700 });
    await fs.rename(temporary, launcher);
  } finally { await fs.rm(temporary, { force: true }); }
  return launcher;
}

const VERSIONED = /kimono-(rag-)?mcp-\d+\.\d+\.\d+/;

/** True when an entry launches Kimono from a versioned extension folder or from our stable launcher. */
function isKimonoEntry(entry, launcher) {
  if (!entry || typeof entry !== "object") return false;
  const parts = [entry.command, ...(Array.isArray(entry.args) ? entry.args : [])].filter(part => typeof part === "string");
  return parts.some(part => part === launcher || VERSIONED.test(part));
}

/**
 * Rewrites the Kimono entries of `<root>/.mcp.json` to the stable launcher and refreshes their repositories.
 * With `create`, adds a `kimono` entry (and the file) when none exists. Other servers are never touched.
 */
async function syncMcpJson(root, launcher, repositories, { create = false } = {}) {
  const file = path.join(root, ".mcp.json");
  let document;
  try { document = JSON.parse(await fs.readFile(file, "utf8")); }
  catch (error) {
    if (error.code !== "ENOENT") return { file, changed: false, error: `Unreadable ${file}: ${error.message}` };
    if (!create) return { file, changed: false };
    document = {};
  }
  if (!document || typeof document !== "object" || Array.isArray(document)) return { file, changed: false, error: `${file} is not a JSON object.` };
  const servers = document.mcpServers && typeof document.mcpServers === "object" ? document.mcpServers : {};
  let names = Object.keys(servers).filter(name => isKimonoEntry(servers[name], launcher));
  if (!names.length && create) { servers.kimono = { type: "stdio", env: { AIKIDO_ROOT: root, KIMONO_CORPUS_MODE: "rag", KIMONO_LOG_LEVEL: "error" } }; names = ["kimono"]; }
  if (!names.length) return { file, changed: false };
  const before = JSON.stringify(document);
  for (const name of names) {
    const entry = servers[name];
    const args = Array.isArray(entry.args) ? entry.args : [];
    const rootAt = args.indexOf("--root");
    const serverRoot = rootAt >= 0 && typeof args[rootAt + 1] === "string" ? args[rootAt + 1] : root;
    const extra = args.filter(arg => typeof arg === "string" && !VERSIONED.test(arg) && arg !== "serve")
      .filter((arg, index, list) => arg !== "--root" && list[index - 1] !== "--root");
    entry.command = launcher;
    entry.args = ["serve", "--root", serverRoot, ...extra];
    entry.env = { ...(entry.env || {}) };
    if (repositories.length) entry.env.KIMONO_REPOSITORIES = JSON.stringify(repositories);
    else delete entry.env.KIMONO_REPOSITORIES;
  }
  document.mcpServers = servers;
  if (JSON.stringify(document) === before) return { file, changed: false, servers: names };
  await fs.writeFile(file, `${JSON.stringify(document, null, 2)}\n`);
  return { file, changed: true, servers: names };
}

module.exports = { discoverRepositories, mergeRepositories, installLauncher, syncMcpJson, isKimonoEntry };
