#!/usr/bin/env node
// Generates semantic/src/grammars.rs from scripts/tree-sitter-grammars.json.
// Usage: node scripts/generate-grammars.mjs <crate-lib-names.json>  (map crate -> Rust lib name; default: crate with - -> _)
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const table = JSON.parse(readFileSync(path.join(root, 'scripts/tree-sitter-grammars.json'), 'utf8'));
const libs = process.argv[2] ? JSON.parse(readFileSync(process.argv[2], 'utf8')) : {};
const crates = Object.keys(table).filter(key => !key.startsWith('_')).sort();
const lib = crate => libs[crate] ?? crate.replace(/-/g, '_');
const arms = [];
const all = [];
for (const crate of crates) {
  for (const [constant, extensions] of Object.entries(table[crate])) {
    all.push(`        ("${crate.replace(/^tree-sitter-/, '')}${constant === 'LANGUAGE' ? '' : `:${constant.replace(/^LANGUAGE_/, '').toLowerCase()}`}", ${lib(crate)}::${constant}.into()),`);
    if (extensions.length) arms.push(`        ${extensions.map(item => `"${item}"`).join(' | ')} => ${lib(crate)}::${constant}.into(),`);
  }
}
writeFileSync(path.join(root, 'semantic/src/grammars.rs'), `// @generated by scripts/generate-grammars.mjs from scripts/tree-sitter-grammars.json. Do not edit.
//! Third-party Tree-sitter grammars (crates.io, ABI-compatible with tree-sitter 0.27).
//! Official grammars are matched first in main.rs; these cover every other bundled language.

/// Grammar for a lower-case file extension, when a third-party grammar owns it.
pub fn language_for(extension: &str) -> Option<tree_sitter::Language> {
    Some(match extension {
${arms.join('\n')}
        _ => return None,
    })
}

/// Generic definition kinds for third-party grammars, which have no hand-written rules.
pub fn is_generic_definition(kind: &str) -> bool {
    const SUBJECTS: [&str; 30] = [
        "function", "method", "procedure", "subroutine", "class", "struct", "module", "interface",
        "trait", "enum", "type", "record", "macro", "namespace", "package", "object", "impl",
        "protocol", "extension", "union", "schema", "message", "service", "rule", "task", "test",
        "contract", "event", "modifier", "resource",
    ];
    const FORMS: [&str; 8] = [
        "_definition", "_declaration", "_item", "_statement", "_specification", "_decl", "_def", "_block",
    ];
    SUBJECTS.iter().any(|subject| {
        kind == *subject
            || FORMS.iter().any(|form| {
                kind.strip_suffix(form).is_some_and(|head| head == *subject || head.ends_with(&format!("_{subject}")))
            })
    })
}

/// Every third-party grammar, by name (verifies that each one links and loads).
#[cfg(test)]
pub fn all() -> Vec<(&'static str, tree_sitter::Language)> {
    vec![
${all.join('\n')}
    ]
}
`);
console.log(`grammars.rs: ${crates.length} crates, ${arms.length} extension groups, ${all.length} languages`);
